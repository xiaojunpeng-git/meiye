import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const workbench = read('前端代码/cashier-v3/src/views/CashierWorkbenchView.vue')
const shell = read('前端代码/cashier-v3/src/layouts/CashierShell.vue')
const rechargeCheckout = read('前端代码/cashier-v3/src/composables/useRechargeCheckout.js')
const manifest = read('前端代码/cashier-v3/src/services/cashierV3ActionManifest.js')
const bridge = read('前端代码/cashier-v3/src/services/cashierV3Bridge.js')
const selector = read('前端代码/cashier-v3/src/components/cashier/CheckoutBusinessSourceOverlay.vue')
const checkoutOverlay = read('前端代码/cashier-v3/src/components/cashier/CashierCheckoutOverlay.vue')

assert.match(workbench, /loadCheckoutBusinessCatalog/, '来源选择器必须只读取正式收银配置目录')
assert.match(workbench, /update-checkout-business-source/, '销售结账必须保留来源编辑动作名称')
assert.doesNotMatch(rechargeCheckout, /update-recharge-checkout-business-source/, '充值来源随本次唯一快照提交，不恢复旧草稿命令')
const normalSourceStart = workbench.indexOf('const localCheckoutBusinessSource')
assert.ok(normalSourceStart >= 0, '本地来源状态必须存在')
const normalSourceEnd = workbench.indexOf('\n})', normalSourceStart)
assert.ok(normalSourceEnd > normalSourceStart, '本地来源状态边界必须明确，不能截取整页')
const normalSourceSection = workbench.slice(normalSourceStart, normalSourceEnd)
assert.doesNotMatch(normalSourceSection, /sourceSelectionVersion/, '普通销售来源不得携带选择版本')
assert.match(workbench, /sourceSelectable === false/, '补交来源必须由后端投影为不可修改')
assert.match(workbench, /localCheckoutBusinessSource/, '销售来源更新必须只写浏览器快照')
assert.match(manifest, /'submit-recharge-checkout'/, '充值最终快照必须使用正式充值权限命令')
assert.match(bridge, /submit-recharge-checkout/, '桥接层必须支持唯一充值快照提交')
assert.match(shell, /cashier-workflow-toolbar__context-settings/, '收银操作工具栏必须承载业务日期与客户来源入口')
assert.match(shell, /cashier-v3:open-toolbar-business-source/, '工具栏来源入口必须打开原有来源选择弹层')
assert.match(shell, /member-selector-selected[\s\S]*open-toolbar-business-source/, '选择会员后必须自动打开客户来源弹层')
assert.match(shell, /function selectGuestOrderFromSelector[\s\S]*applyLocalCashierCustomerSelection/, '切换游客必须走本地客户草稿')
assert.match(shell, /function applyLocalCashierCustomerSelection[\s\S]*clear-toolbar-business-source/, '切换游客必须清空客户来源')
assert.match(shell, /cashier-v3:update-toolbar-business-date/, '工具栏业务日期必须回填前端结账快照')
assert.match(workbench, /localCheckoutBusinessSource/, '客户来源必须先保存在浏览器结账快照')
assert.match(workbench, /if \(kind !== 'recharge'\) \{[\s\S]*localCheckoutBusinessSource/, '普通销售来源只能保留前端工具栏值')
assert.match(workbench, /function saveCheckoutSalesDate[\s\S]*localDraftResult\('业务日期已回填到工具栏结账上下文。'\)/, '普通销售业务日期只能保留前端工具栏值')
assert.match(workbench, /handleToolbarBusinessSourceClear[\s\S]*primarySourceId: 0/, '游客切换必须清零本地来源快照')
assert.match(workbench, /Number\(state\.businessSourceDefaultsMemberId \?\? -1\) === currentId/, '游客和会员默认来源必须绑定各自身份，不能借用上一会员投影')
assert.match(workbench, /selector\.kind !== 'recharge' && !isCheckoutOpen\.value/, '结账未打开时普通销售来源必须绕过旧结账投影')
assert.match(workbench, /localCheckoutBusinessDate/, '业务日期必须先保存在浏览器结账快照')
assert.match(workbench, /serviceObject: cartLineServiceObject\(line\)/, '结账快照必须读取当前页面服务对象')
assert.match(workbench, /friendCountsAsCustomer: cartLineFriendCountsAsCustomer\(line\)/, '结账快照必须读取当前本人朋友计客口径')
assert.match(selector, /来源在收银编辑阶段只是用户选择的快照字段/, '来源选择器必须按新口径只回填、不做二级来源拦截')
assert.doesNotMatch(selector, /if \(requiresSecondary\.value && !secondaryId\.value\)/, '来源选择器不得因二级来源配置阻断回填')
assert.match(selector, /emit\('confirm', \{ primarySourceId: primaryId.value, secondarySourceId: secondaryId.value, rewardAmountCents \}\)/, '前端只能提交来源 ID 与整数分奖励金额，名称由后端快照')
assert.doesNotMatch(checkoutOverlay, /v-if="isRechargeCheckout && checkout\.sourceEnabled"/, '充值结账不重复展示来源选择')
assert.match(workbench, /sourceEnabled: businessSourceEnabled\.value/, '页面来源显隐必须服从实例策略')
assert.match(workbench, /checkout-business-source-confirmed/, '来源确认后必须通知待办流程继续')
assert.match(workbench, /hasCommittedSubmitReceipt[\s\S]*checkoutLocalOutcome\.value = \{[\s\S]*status: 'succeeded'/, '最终提交回执即使携带清空根状态也必须进入成功结果页')
console.log('cashier business-source checkout frontend contract: PASS')
