import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8')
const workbench = read('前端代码/cashier-v3/src/views/CashierWorkbenchView.vue')
const shell = read('前端代码/cashier-v3/src/layouts/CashierShell.vue')
const rechargeCheckout = read('前端代码/cashier-v3/src/composables/useRechargeCheckout.js')
const manifest = read('前端代码/cashier-v3/src/services/cashierV3ActionManifest.js')
const bridge = read('前端代码/cashier-v3/src/services/cashierV3Bridge.js')
const selector = read('前端代码/cashier-v3/src/components/cashier/CheckoutBusinessSourceOverlay.vue')
const checkoutOverlay = read('前端代码/cashier-v3/src/components/cashier/CashierCheckoutOverlay.vue')

assert.match(workbench, /loadCheckoutBusinessCatalog/, '来源选择器必须只读取正式收银配置目录')
assert.match(workbench, /update-checkout-business-source/, '销售结账必须提交正式来源更新命令')
assert.match(rechargeCheckout, /update-recharge-checkout-business-source/, '充值结账必须提交正式来源更新命令')
assert.match(workbench, /sourceSelectionVersion/, '来源更新必须携带独立选择版本')
assert.match(workbench, /sourceSelectable === false/, '补交来源必须由后端投影为不可修改')
assert.match(manifest, /'update-checkout-business-source': FEATURE_CASHIER/, '销售来源更新必须登记为收银命令')
assert.match(manifest, /'update-recharge-checkout-business-source': FEATURE_MEMBER/, '充值来源更新必须登记为会员命令')
assert.match(bridge, /action === 'update-recharge-checkout-business-source'/, '充值来源更新必须带会员和余额版本上下文')
assert.match(shell, /cashier-workflow-toolbar__context-settings/, '收银操作工具栏必须承载业务日期与客户来源入口')
assert.match(shell, /cashier-v3:open-toolbar-business-source/, '工具栏来源入口必须打开原有来源选择弹层')
assert.match(shell, /member-selector-selected[\s\S]*open-toolbar-business-source/, '选择会员后必须自动打开客户来源弹层')
assert.match(shell, /cashier-v3:update-toolbar-business-date/, '工具栏业务日期必须回填前端结账快照')
assert.match(workbench, /localCheckoutBusinessSource/, '客户来源必须先保存在浏览器结账快照')
assert.match(workbench, /selector\.kind !== 'recharge' && !isCheckoutOpen\.value/, '结账未打开时普通销售来源必须绕过旧结账投影')
assert.match(workbench, /localCheckoutBusinessDate/, '业务日期必须先保存在浏览器结账快照')
assert.match(selector, /来源在收银编辑阶段只是用户选择的快照字段/, '来源选择器必须按新口径只回填、不做二级来源拦截')
assert.doesNotMatch(selector, /if \(requiresSecondary\.value && !secondaryId\.value\)/, '来源选择器不得因二级来源配置阻断回填')
assert.match(selector, /emit\('confirm', \{ primarySourceId: primaryId.value, secondarySourceId: secondaryId.value, rewardAmountCents \}\)/, '前端只能提交来源 ID 与整数分奖励金额，名称由后端快照')
assert.match(checkoutOverlay, /v-if="isRechargeCheckout && checkout\.sourceEnabled"/, '普通销售结账不得重复显示客户来源，充值兼容旧流程')
assert.match(checkoutOverlay, /v-if="isRechargeCheckout" class="checkout-order-details checkout-order-details--source-date"/, '普通销售结账不得重复显示业务日期，充值兼容旧流程')
assert.match(workbench, /checkout-business-source-confirmed/, '来源确认后必须通知待办流程继续')
console.log('cashier business-source checkout frontend contract: PASS')
