import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const source = fs.readFileSync(path.join(root, '前端代码/cashier-v3/src/components/member/RechargeOverlay.vue'), 'utf8')
const shell = fs.readFileSync(path.join(root, '前端代码/cashier-v3/src/layouts/CashierShell.vue'), 'utf8')
const workbench = fs.readFileSync(path.join(root, '前端代码/cashier-v3/src/views/CashierWorkbenchView.vue'), 'utf8')
const rechargeCheckout = fs.readFileSync(path.join(root, '前端代码/cashier-v3/src/composables/useRechargeCheckout.js'), 'utf8')
const checkoutOverlay = fs.readFileSync(path.join(root, '前端代码/cashier-v3/src/components/cashier/CashierCheckoutOverlay.vue'), 'utf8')
const bridge = fs.readFileSync(path.join(root, '前端代码/cashier-v3/src/services/cashierV3Bridge.js'), 'utf8')

let passed = 0
function expect(name, condition) {
  if (!condition) throw new Error(`FAIL ${name}`)
  passed += 1
  console.log(`PASS ${name}`)
}

expect('桌面套餐固定一行四项', source.includes('grid-template-columns: repeat(4, minmax(0, 1fr))'))
expect('套餐金额明确为本金且赠送位于右下', source.includes('class="recharge-overlay__package-main"')
  && source.includes('本金 {{ formatMoney(item.price) }}')
  && source.includes('grid-column: 2; grid-row: 2'))
expect('套餐摘要独立位于主金额区下一行', source.includes('<small v-if="item.giftProductCount || item.giftCouponCount">'))
expect('套餐模式不渲染重复本金与赠送输入', source.includes('<template v-if="rechargeMode === \'custom\'">')
  && source.includes(':class="{ \'recharge-overlay__fields--custom\': rechargeMode === \'custom\' }"'))
expect('自定义充值的本金赠送欠款固定三列', source.includes('.recharge-overlay__fields--custom { grid-template-columns: repeat(3, minmax(0, 1fr)); }'))
expect('小高度窗口的充值弹窗可以内部滚动至确认操作', source.includes('max-height: calc(100vh - 48px)')
  && source.includes('overflow-y: auto'))
expect('金额仅允许整数元', source.includes("if (!/^(0|[1-9]\\d*)$/.test(raw)) return false")
  && source.includes("const match = /^(0|[1-9]\\d*)$/.exec(raw)"))
expect('充值各金额保留原输入并由整数元校验明确拒绝小数', source.includes('function normalizePrincipalAmount(event)')
  && source.includes('function normalizeBonusAmount(event)')
  && source.includes('function normalizeDebtAmount(event)')
  && source.includes('@input="normalizePrincipalAmount"')
  && source.includes('@input="normalizeBonusAmount"')
  && source.includes('@input="normalizeDebtAmount"')
  && !source.includes('Math.trunc(')
  && !source.includes('parseInt('))
expect('充值销售人复用购物车人员选择与比例', source.includes('PersonnelPerformanceOverlay')
  && source.includes(':show-craftsmen="false"')
  && source.includes('allocationWeight: Number(item.allocationWeight)')
  && !source.includes('整数业绩金额'))
expect('充值入口不再直接编辑收款明细', !source.includes('class="recharge-overlay__payments"')
  && !source.includes('paymentLines: paymentLines.value.map'))
expect('充值先准备独立 Checkout 再编辑收款', workbench.includes("requestCashierV3Action('prepare-recharge-checkout'")
  && rechargeCheckout.includes("'add-recharge-checkout-payment-method'")
  && rechargeCheckout.includes("'submit-recharge-checkout'"))
expect('V3 收银台由 Shell 将充值快照交给新 Checkout', shell.includes("overlayName === 'recharge'")
  && shell.includes("new CustomEvent('cashier-v3:open-recharge'")
  && shell.includes('detail: overlay')
  && shell.includes('v-if="rechargeSession && !isCashierPage"'))
expect('充值准备结果未知不误报已受理', shell.includes("action === 'prepare-recharge-checkout'")
  && shell.includes('收款准备未完成')
  && shell.includes('尚未进入收款，也未扣款'))
expect('桥接层对充值准备结果使用同一安全语义', bridge.includes("canonicalAction === 'prepare-recharge-checkout'")
  && bridge.includes('尚未进入收款或扣款'))
expect('充值准备结果未知沿用原请求标识重试', workbench.includes('rechargePreparationIdempotencyKey')
  && workbench.includes('idempotencyKey: rechargePreparationIdempotencyKey.value')
  && workbench.includes('rechargePreparationIdempotencyKey.value = String(response.idempotencyKey || \'\')'))
expect('充值 Checkout 操作按响应串行', rechargeCheckout.includes('let rechargeCheckoutMutationTail = Promise.resolve()')
  && rechargeCheckout.includes('async function enqueueRechargeCheckoutAction(event = {})'))
expect('充值提交结果未知不再永久停留编辑锁', rechargeCheckout.includes('result_unknown')
  && rechargeCheckout.includes('processingLong')
  && rechargeCheckout.includes('rechargeCheckout.value = {'))
expect('充值提交失败会解除前端提交锁并提示', checkoutOverlay.includes('handleSubmissionResponse')
  && checkoutOverlay.includes("isSubmitRequested.value = false")
  && checkoutOverlay.includes("request('submit-checkout'")
  && workbench.includes('event?.resolve?.(result)'))
expect('充值提交超时自动查询原请求', checkoutOverlay.includes('submissionQueryTimer')
  && checkoutOverlay.includes('queryOriginalCheckoutResult()')
  && checkoutOverlay.includes('isRechargeCheckout.value'))
expect('充值草稿每次响应同步收款请求版本', rechargeCheckout.includes("kind: 'recharge_checkout_request'")
  && rechargeCheckout.includes('checkoutRequestVersion')
  && rechargeCheckout.includes('mergeCashierV3PublicVersions'))
expect('充值收款编辑回传统一清理挂起状态事件', rechargeCheckout.includes("cashier-v3:checkout-draft-mutation-result")
  && rechargeCheckout.includes("['add-payment-method', 'update-payment-line', 'remove-payment-line', 'update-checkout-business-source']"))
expect('充值草稿编辑失败留在收款页并由局部弹窗处理', rechargeCheckout.includes('allowTerminalOutcome: !draftAction')
  && rechargeCheckout.includes('silent: draftAction')
  && rechargeCheckout.includes('allowTerminalOutcome'))
expect('收款金额变更事件也会保存草稿', checkoutOverlay.includes('@change="savePaymentLineAmount(line, paymentLineInputAmount(line))"'))
expect('充值 Checkout 复用客户来源目录与保存回调', workbench.includes('loadInlineRechargeBusinessSources')
  && workbench.includes('@business-source-change="saveInlineRechargeBusinessSource"')
  && workbench.includes(':business-sources="checkoutInlineBusinessSources"'))
expect('收款结果状态统一显示中文', checkoutOverlay.includes("if (['succeeded', 'success', 'completed'].includes(normalizedStatus)) return '成功'")
  && checkoutOverlay.includes("if (['editing', '待确认'].includes(normalizedStatus)")
  && !checkoutOverlay.includes('return line.status || line.paymentStatus || line.resultStatus || \'待收款\''))

console.log(`RECHARGE_OVERLAY_FRONTEND_CONTRACT_OK passed=${passed}`)
