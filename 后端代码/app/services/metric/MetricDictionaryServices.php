    public function getByCode(string $code): ?array
    {
        foreach ($this->getDefinitions() as $item) {
            if (($item['code'] ?? '') === $code) {
                return $item;
            }
        }
        return null;
    }

    /**
     * 前端 ⓘ 口径说明（仅自然语言，给一线用户看）
