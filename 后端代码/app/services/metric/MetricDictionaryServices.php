    public function getTooltip(string $code): array
    {
        $item = $this->getByCode($code);
        if (!$item) {
            return [
                'code' => $code,
                'name' => '',
                'user_ready' => false,
                'summary' => '指标未定义',
                'include' => '',
                'exclude' => '',
                'timing' => '',
                'note' => '',
            ];
        }

        $ready = !empty($item['user_ready']);
        if (!$ready) {
            return [
                'code' => $item['code'],
                'name' => $item['name'],
                'user_ready' => false,
                'summary' => '口径说明待产品确认，暂不展示技术说明。',
                'include' => '',
                'exclude' => '',
                'timing' => '',
                'note' => '',
                'updated_at' => date('Y-m-d H:i:s'),
                'version' => '2.0.0',
            ];
        }

        return [
            'code' => $item['code'],
            'name' => $item['name'],
            'user_ready' => true,
            'summary' => (string)($item['summary'] ?? ''),
            'include' => (string)($item['include'] ?? ''),
