-- R26 unified manual refunds. One successful command produces one immutable target adjustment.
-- Amounts are cents; balance grants are independent of the recorded refund amount.
CREATE TABLE IF NOT EXISTS `eb_cashier_v3_refund_adjustment` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `adjustment_id` varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `operation_id` varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `command_idempotency_key` varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `tenant_id` varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `store_id` bigint(20) unsigned NOT NULL,
  `member_id` bigint(20) unsigned NOT NULL,
  `operator_id` bigint(20) unsigned NOT NULL,
  `target_type` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `card_holder_id` bigint(20) unsigned NOT NULL DEFAULT '0',
  `card_component_id` bigint(20) unsigned NOT NULL DEFAULT '0',
  `source_order_id` varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `source_line_id` varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  `source_order_no_snapshot` varchar(64) NOT NULL,
  `target_name_snapshot` varchar(255) NOT NULL,
  `refund_amount_cents` bigint(20) unsigned NOT NULL,
  `balance_credit_cents` bigint(20) unsigned NOT NULL DEFAULT '0',
  `balance_kind` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `remaining_before_cents` bigint(20) unsigned NOT NULL,
  `remaining_after_cents` bigint(20) unsigned NOT NULL,
  `closed_remaining_cents` bigint(20) unsigned NOT NULL DEFAULT '0',
  `times_before` bigint(20) unsigned NOT NULL DEFAULT '0',
  `times_after` bigint(20) unsigned NOT NULL DEFAULT '0',
  `times_removed` bigint(20) unsigned NOT NULL DEFAULT '0',
  `times_closed` bigint(20) unsigned NOT NULL DEFAULT '0',
  `valid_through_before` bigint(20) unsigned NOT NULL DEFAULT '0',
  `valid_through_after` bigint(20) unsigned NOT NULL DEFAULT '0',
  `void_target` tinyint(1) unsigned NOT NULL DEFAULT '0',
  `reason_snapshot` varchar(255) NOT NULL,
  `business_date` date NOT NULL,
  `occurred_at` bigint(20) unsigned NOT NULL,
  `settled_at` bigint(20) unsigned NOT NULL,
  `recorded_at` bigint(20) unsigned NOT NULL,
  `status` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_adjustment_id` (`adjustment_id`),
  UNIQUE KEY `uk_operation_id` (`operation_id`),
  UNIQUE KEY `uk_command` (`tenant_id`,`command_idempotency_key`),
  KEY `idx_card` (`tenant_id`,`card_holder_id`,`id`),
  KEY `idx_component` (`tenant_id`,`card_component_id`,`id`),
  KEY `idx_line` (`tenant_id`,`source_line_id`,`id`),
  KEY `idx_scope_date` (`tenant_id`,`store_id`,`business_date`,`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='R26 append-only card and document refund adjustments';
